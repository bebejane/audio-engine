/**
 * Assembles the effects AudioWorklet source from the per-effect fragments.
 *
 *   src/effects/worklet/*.js     shared helpers (read first, in the order
 *                                      listed below)
 *   src/effects/<effect>/source.js
 *                                      one effect's processor + registration
 *
 * The fragments are plain worklet-scope code (no import/export, no modules),
 * concatenated into one script and written to workletsource.generated.ts as a
 * JSON-escaped string (so the fragments may freely contain backticks / ${).
 *
 * Run: pnpm worklet:gen        (or node scripts/build-effects-worklet.mjs)
 * Check: pnpm worklet:check    (fails if the generated file is stale)
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const effectsDir = join(root, 'src/effects');
const sharedDir = join(effectsDir, 'worklet');
const outFile = join(effectsDir, 'workletsource.generated.ts');

// shared fragments, in dependency order (core helpers first)
// channel.js is the per-sound channel processor used directly by Sound (loop
// clock + anti-click fade + elapsed), not an effect
const SHARED = ['core.js', 'channel.js'];

const read = (path) => readFileSync(path, 'utf8').trim();

const parts = SHARED.map((f) => {
	const path = join(sharedDir, f);
	if (!existsSync(path)) throw new Error('missing shared fragment: ' + path);
	return { name: 'worklet/' + f, code: read(path) };
});

for (const dirent of readdirSync(effectsDir, { withFileTypes: true })) {
	if (!dirent.isDirectory() || dirent.name === 'worklet') continue;
	const path = join(effectsDir, dirent.name, 'source.js');
	if (existsSync(path)) parts.push({ name: dirent.name + '/source.js', code: read(path) });
}

for (const part of parts) {
	// fragments are concatenated as one script, so they must not be modules
	if (/^\s*(import|export)\b/m.test(part.code)) {
		throw new Error(part.name + ' must be a plain script fragment (no import/export)');
	}
}

const code = parts.map((p) => p.code).join('\n\n');
new Function(code); // syntax check only (does not execute the processors)

const output =
	'// AUTO-GENERATED by scripts/build-effects-worklet.mjs — do not edit by hand.\n' +
	'// Sources: src/effects/worklet/*.js + src/effects/*/source.js\n' +
	'export const EFFECTS_WORKLET_SOURCE = ' +
	JSON.stringify(code) +
	';\n';

const summary = parts.length + ' fragments, ' + code.length + ' bytes';

if (process.argv.includes('--check')) {
	const current = existsSync(outFile) ? readFileSync(outFile, 'utf8') : '';
	if (current !== output) {
		console.error('workletsource.generated.ts is stale — run "pnpm worklet:gen"');
		process.exit(1);
	}
	console.log('worklet source up to date (' + summary + ')');
} else {
	writeFileSync(outFile, output);
	console.log('wrote src/effects/workletsource.generated.ts (' + summary + ')');
}
